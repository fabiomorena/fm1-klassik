# Changed 2026 by fabiomorena: msfa's init() functions, which fill its tables at start-up with double maths, as a
#   generator that writes them as a C header at build time (the FM-1 has no double); the block 32 samples (LG_N 5).
"""The tables of KLASSIK's FM6 (dsp/fm6/msfa.c), as msfa's init() functions make them at start-up.

  gen_fm6_tables.py [--fs RATE] fm6_tables.h

msfa (https://github.com/google/music-synthesizer-for-android, app/src/main/jni/) fills these at start-up with
double maths: Sin::init, Exp2::init, Freqlut::init, Lfo::init and PitchEnv::init, and osc_freq's fine frequency
(a log a note). Here they are made once, with the same operations in the same order (Python's float is the same
IEEE double, its math functions C's libm), and written as constant tables for the flash:
  FM_SINTAB[2048]     a sine period, Q24, each value after its step to the next (msfa's SIN_DELTA layout)
  FM_EXP2TAB[2048]    2^x over an octave, Q30, the same layout
  FM_FREQLUT[1025]    an octave of phase increments (msfa's lut)
  FM_FINE[100]        osc_freq's fine frequency 0..99 in Q24 octaves
  FM_LFO_UNIT, FM_PITCHENV_UNIT   Lfo's and PitchEnv's unit_ at this rate and block
"""
import argparse
import math
import sys

LG_N = 5                         # a block: 32 samples (msfa's LG_N is 6); dsp/fm6/msfa.h FM_LG_N
N = 1 << LG_N
SIN_LG_N_SAMPLES = 10
EXP2_LG_N_SAMPLES = 10
FREQ_LG_N_SAMPLES = 10
MAX_LOGFREQ_INT = 20


def i32(x):
    """C's conversion of a value that fits to int32_t (the generator checks it fits)"""
    if not -(1 << 31) <= x < (1 << 31):
        raise SystemExit(f"gen_fm6_tables: {x} does not fit an int32_t")
    return x


def sintab():
    """Sin::init with SIN_DELTA: a quarter-turn rotation in Q30 integers, the sine at [2i + 1], its step at [2i]"""
    n = 1 << SIN_LG_N_SAMPLES
    r = 1 << 29
    dphase = 2 * math.pi / n
    c = math.floor(math.cos(dphase) * (1 << 30) + 0.5)
    s = math.floor(math.sin(dphase) * (1 << 30) + 0.5)
    u, v = 1 << 30, 0
    t = [0] * (n << 1)
    for i in range(n // 2):
        t[(i << 1) + 1] = (v + 32) >> 6
        t[((i + n // 2) << 1) + 1] = -((v + 32) >> 6)
        nt = (u * s + v * c + r) >> 30
        u = (u * c - v * s + r) >> 30
        v = nt
    for i in range(n - 1):
        t[i << 1] = t[(i << 1) + 3] - t[(i << 1) + 1]
    t[(n << 1) - 2] = -t[(n << 1) - 1]
    return [i32(x) for x in t]


def exp2tab():
    """Exp2::init: 2^(i / 1024) in Q30 at [2i + 1], its step at [2i]"""
    n = 1 << EXP2_LG_N_SAMPLES
    inc = math.exp2(1.0 / n)
    y = float(1 << 30)
    t = [0] * (n << 1)
    for i in range(n):
        t[(i << 1) + 1] = math.floor(y + 0.5)
        y *= inc
    for i in range(n - 1):
        t[i << 1] = t[(i << 1) + 3] - t[(i << 1) + 1]
    t[(n << 1) - 2] = (1 << 31) - t[(n << 1) - 1]
    return [i32(x) for x in t]


def freqlut(fs):
    """Freqlut::init: the phase increment of an octave's 1025 steps, from 2^20 times the lowest"""
    n = 1 << FREQ_LG_N_SAMPLES
    y = (1 << (24 + MAX_LOGFREQ_INT)) / fs
    inc = math.pow(2, 1.0 / n)
    t = []
    for _ in range(n + 1):
        t.append(i32(math.floor(y + 0.5)))
        y *= inc
    return t


def fine():
    """osc_freq (ratio mode): FINE 0..99 as (1 << 24) / log(2) * log(1 + FINE / 100), rounded"""
    return [i32(math.floor(24204406.323123 * math.log(1 + 0.01 * f) + 0.5)) if f else 0 for f in range(100)]


def arr(name, vals, per=8):
    rows = [", ".join(str(v) for v in vals[i:i + per]) for i in range(0, len(vals), per)]
    return f"static const int32_t {name}[{len(vals)}] = {{\n    " + ",\n    ".join(rows) + "\n};\n"


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--fs", type=int, default=44100, help="the sample rate (the engines' FS)")
    ap.add_argument("out")
    a = ap.parse_args()
    if not hasattr(math, "exp2"):
        raise SystemExit("gen_fm6_tables: needs Python 3.11 or newer (math.exp2, as msfa's exp2)")
    lfo_unit = int(N * 25190424 / a.fs + 0.5)                 # Lfo::init: 1 << 32 / 15.5 s / 11, a block
    pitchenv_unit = int(N * (1 << 24) / (21.3 * a.fs) + 0.5)  # PitchEnv::init
    h = ["/* SPDX-License-Identifier: Apache-2.0", " * Copyright 2012, 2013 Google Inc.",
         f" * Generated by firmware/klassik/tools/gen_fm6_tables.py --fs {a.fs}: msfa's tables (see there). */",
         "#pragma once", "#include <stdint.h>", "",
         f"#define FM_GEN_FS {a.fs}", f"#define FM_GEN_LG_N {LG_N}",
         f"#define FM_LFO_UNIT {lfo_unit}u", f"#define FM_PITCHENV_UNIT {pitchenv_unit}", "",
         arr("FM_SINTAB", sintab()), arr("FM_EXP2TAB", exp2tab()), arr("FM_FREQLUT", freqlut(a.fs)),
         arr("FM_FINE", fine())]
    with open(a.out, "w") as f:
        f.write("\n".join(h))
    return 0


if __name__ == "__main__":
    sys.exit(main())
